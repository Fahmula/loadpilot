"""Regenerates loadpilot/icons.py from the Lucide icon set (https://lucide.dev, ISC license).

To add an icon, append its Lucide name to ICONS and run:

    curl -fsSL https://registry.npmjs.org/lucide-static/-/lucide-static-<version>.tgz | tar -xz -C /tmp
    python scripts/generate_icons.py /tmp/package
"""

import json
import re
import sys
from pathlib import Path

ICONS = [
    "arrow-left", "arrow-right", "bell", "building-2", "calendar", "camera", "chart-line", "check",
    "chevron-down", "chevron-left", "chevron-right", "circle-alert", "circle-check", "circle-dollar-sign",
    "clock", "cloud-upload", "coins", "cpu", "dollar-sign", "download", "external-link", "file", "file-check",
    "file-text", "file-up", "files", "gauge", "hash", "info", "key-round", "landmark", "list",
    "loader-circle", "lock", "log-in", "log-out", "mail", "map-pin", "monitor", "moon", "package",
    "package-check", "paperclip", "pencil", "plus", "receipt", "road", "route", "search", "settings",
    "sparkles", "sticky-note", "sun", "trash-2", "trending-down", "trending-up", "truck", "user", "user-plus",
    "x", "zoom-in", "fuel", "wallet", "wrench", "shield", "square-parking", "piggy-bank",
]  # fmt: skip

OUTPUT = Path(__file__).resolve().parents[1] / "loadpilot" / "icons.py"


def inner_svg(svg: str) -> str:
    body = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
    return re.sub(r"\s+", " ", body).replace("> <", "><").strip()


def main(package_dir: str):
    package = Path(package_dir)
    version = json.loads((package / "package.json").read_text())["version"]
    icons = {name: inner_svg((package / "icons" / f"{name}.svg").read_text()) for name in sorted(ICONS)}

    lines = [
        f'"""Lucide icons v{version} (ISC license, https://lucide.dev). Generated by scripts/generate_icons.py."""',
        "",
        "# fmt: off",
        "ICONS = {",
        *(f"    {name!r}: {markup!r}," for name, markup in icons.items()),
        "}",
        "",
    ]
    OUTPUT.write_text("\n".join(lines))
    print(f"Wrote {len(icons)} icons to {OUTPUT}")


if __name__ == "__main__":
    main(sys.argv[1])
